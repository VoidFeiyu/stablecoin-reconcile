  function translator(language, catalog) {
    const index = language === "en" ? 0 : language === "zh-Hant" ? 1 : -1;
    return (key, ...values) => {
      const template = index < 0 ? key : catalog[key]?.[index] ?? key;
      return template.replace(/\{(\d+)\}/g, (match, position) => position < values.length ? String(values[position]) : match);
    };
  }

  function apply(root, translate) {
    const document = root.ownerDocument ?? root;
    const walker = document.createTreeWalker(root, 4);
    for (let node = walker.nextNode(); node; node = walker.nextNode()) {
      if (node.parentElement?.closest("script, style, textarea")) continue;
      const key = node.data.trim();
      if (key) node.data = node.data.replace(key, () => translate(key));
    }
    for (const element of root.querySelectorAll("[aria-label], [placeholder], [title], meta[name=description]")) {
      for (const name of ["aria-label", "placeholder", "title", "content"]) {
        const value = element.getAttribute(name);
        if (value) element.setAttribute(name, translate(value));
      }
    }
  }

  function choose(value) {
    return supported.includes(value) ? value : "zh-Hans";
  }

  function initialLanguage() {
    if (typeof window === "undefined") return "zh-Hans";
    const requested = new URL(window.location.href).searchParams.get("lang");
    if (supported.includes(requested)) return requested;
    try {
      const saved = window.localStorage.getItem(preference);
      if (supported.includes(saved)) return saved;
    } catch {
      // Language selection still works through the URL when storage is unavailable.
    }
    const browser = window.navigator.language;
    if (/^zh-(?:Hant|TW|HK|MO)(?:-|$)/i.test(browser)) return "zh-Hant";
    return /^en(?:-|$)/i.test(browser) ? "en" : "zh-Hans";
  }

  const language = initialLanguage();
  const t = translator(language, messages);

  function changeLanguage(value) {
    const requested = choose(value);
    if (requested === language) return;
    const url = new URL(window.location.href);
    try {
      window.localStorage.setItem(preference, requested);
      url.searchParams.delete("lang");
    } catch {
      url.searchParams.set("lang", requested);
    }
    if (url.href === window.location.href) window.location.reload();
    else window.location.replace(url.href);
  }

  function activity(value) {
    const formats = [
      [/^新增账单 (.+)$/, "新增账单 {0}"],
      [/^已编辑账单 ([\s\S]+)$/, "已编辑账单 {0}"],
      [/^导入 (\d+) 张账单$/, "导入 {0} 张账单"],
      [/^关联账单 (.+) · (.+)$/, "关联账单 {0} · {1}"],
      [/^批量关联 (.+)$/, "批量关联 {0}"],
      [/^撤销账单 (.+) 的关联$/, "撤销账单 {0} 的关联"],
      [/^标记异常 (.+?) · ([\s\S]+)$/, "标记异常 {0} · {1}"],
      [/^恢复待匹配 (.+)$/, "恢复待匹配 {0}"],
      [/^从备份恢复 (\d+) 条记录$/, "从备份恢复 {0} 条记录"]
    ];
    for (const [pattern, key] of formats) {
      const match = pattern.exec(value);
      if (match) return t(key, ...match.slice(1));
    }
    return value;
  }

  return {activity, apply, changeLanguage, choose, language, messages, supported, t, translator};
